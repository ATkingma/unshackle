using System.Reflection;
using Unshackle.Core.Models;

namespace Unshackle.Core.Fixes.MediatR;

// Ardalis.SharedKernel up to 3.0.1 builds on MediatR (DomainEventBase : INotification, ICommand<T> : IRequest<T>). 4.0.0 moved to
// Mediator, but dropped ICommand, IQuery and their handlers and needs net9.0: an upgrade is not the same API. So its source (MIT),
// with Mediator in place of MediatR, goes into the solution instead; same namespace, names and behavior (TAAK-194).
// Source in Vendored/ArdalisSharedKernel: common/ for every version, plus the folder of the version's source family.
internal static class ArdalisSharedKernel
{
    public const string Name = "Ardalis.SharedKernel";

    private const string Resources = "MediatR/Vendored/ArdalisSharedKernel/";

    private const string Header =
        "// <auto-generated>\n" +
        "//   Ardalis.SharedKernel {version} (MIT, Copyright (c) 2022 Steve Smith; see LICENSE.txt in this folder), put here by Unshackle:\n" +
        "//   the package builds on MediatR, this copy on Mediator. Same namespace, types and behavior.\n" +
        "// </auto-generated>\n" +
        "#nullable enable\n" +
        "\n";

    public static VendoredPackage Package { get; } = new()
    {
        Name = Name,
        Folder = Name,
        Header = Header,
        ExtraFiles = [new() { Name = "LICENSE.txt", Text = Read("LICENSE.txt") }],
        // The dependencies and their versions are those of the package's nuspec.
        Versions =
        [
            Version("1.4.0", "1.4.0", "4.1.1", "7.0.0", "7.0.1"),
            Version("1.5.0", "1.5.0", "4.1.1", "7.0.0", "7.0.1"),
            Version("1.6.0", "1.5.0", "4.6.0", "8.0.0", "8.0.1"),
            Version("2.1.0", "2.1.0", "4.6.0", "8.0.0", "8.0.1"),
            Version("2.1.1", "2.1.0", "5.0.0", "8.0.0", "8.0.2"),
            Version("3.0.1", "2.1.0", "5.0.0", "9.2.0", "9.0.6"),
        ],
    };

    private static VendoredVersion Version(string version, string family, string guardClauses, string specification, string logging) => new()
    {
        Version = version,
        Files = [.. Files("common/").Concat(Files(family + "/")).OrderBy(f => f.Name, StringComparer.Ordinal)],
        Dependencies =
        [
            new() { Name = "Ardalis.GuardClauses", Version = guardClauses },
            new() { Name = "Ardalis.Specification", Version = specification },
            new() { Name = "Microsoft.Extensions.Logging.Abstractions", Version = logging },
        ],
    };

    private static IEnumerable<VendoredFile> Files(string folder) =>
        ResourceNames().Where(n => n.StartsWith(Resources + folder, StringComparison.Ordinal))
            .Select(n => new VendoredFile { Name = n[(Resources.Length + folder.Length)..], Text = Read(n[Resources.Length..]) });

    // Resource names follow the folders under Fixes (Unshackle.Core.csproj); the separator depends on the OS that built it.
    private static IEnumerable<string> ResourceNames() =>
        typeof(ArdalisSharedKernel).Assembly.GetManifestResourceNames().Select(n => n.Replace('\\', '/'));

    private static string Read(string name)
    {
        Assembly assembly = typeof(ArdalisSharedKernel).Assembly;
        string resource = assembly.GetManifestResourceNames().Single(n => n.Replace('\\', '/') == Resources + name);
        using Stream stream = assembly.GetManifestResourceStream(resource)!;
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd().ReplaceLineEndings("\n");
    }
}
